#!/usr/bin/env node
import {readFileSync, rmSync} from "node:fs";
import {resolve} from "node:path";
import {checkLinks} from "./check-links.mjs";
import {createSourceManifest} from "./freeze-design.mjs";
import {experimentRoot, indexBytes, readJson, sha256, stableStringify} from "./lib.mjs";
import {privacyCheck} from "./privacy-check.mjs";
import {createSchedule} from "./schedule.mjs";
import {verifyNoRun} from "./verify-no-run.mjs";

function assertBytes(path, expected) {
  if (readFileSync(path, "utf8") !== stableStringify(expected)) {
    throw new Error(`frozen generated bytes differ: ${path}`);
  }
}

assertBytes(resolve(experimentRoot, "design", "schedule.json"), createSchedule());
const frozenManifest = readJson(resolve(experimentRoot, "design", "source-manifest.json"));
for (const [path, entry] of Object.entries(frozenManifest.sources)) {
  const bytes = indexBytes(path);
  if (bytes.length !== entry.bytes || sha256(bytes) !== entry.indexSha256) {
    throw new Error(`Git-index source drift: ${path}`);
  }
}
if (stableStringify(frozenManifest) !== stableStringify(createSourceManifest())) {
  throw new Error("generated bundle or source manifest drift");
}
verifyNoRun();
checkLinks();
privacyCheck();
for (let index = 0; index < 8; index += 1) {
  rmSync(resolve(experimentRoot, `.v2-doc-example-${index}.mjs`), {force: true});
}
process.stdout.write("V2 reproduction verified: index bytes, bundles, schedule, links, privacy, no-run\n");
